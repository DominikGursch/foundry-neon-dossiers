// Explicit at-grade junction decisions from the image review. Other geometric crossings stay separate.
const junctions = [
  [815,169],[783,194],[524,519],[520,543],[615,758],[622,762],[645,774],[710,774],
  [961,565],[982,523],[1127,442],[920,415],[937,434],[1053,351],[565,392],[594,484],
  [695,459],[733,459],[718,469],[718,74],[781,74],[715,96],[779,96],[758,186],
  [734,96],[766,96],[821,96],[734,111],[766,111],[821,111],[734,150],[783,187],
  [1225,600],[1256,650],[1150,839],[1140,697],[1178,650],[1280,650],
  [829,633],[727,627],[816,614],[831,638],[810,734],[735,638]
];
for (const [x, y] of junctions) {
  const id = anchors.get(`${x},${y}`) ?? `c${x}-${y}`;
  const p = communityPoint(x, y);
  const changed = [];
  for (const [key, edge] of edges) {
    if (edge.from === id || edge.to === id) continue;
    const a = nodes.get(edge.from), b = nodes.get(edge.to);
    const ax = (a.x * 2519 + 549) / 3615 * 1600, ay = a.y * 1066;
    const bx = (b.x * 2519 + 549) / 3615 * 1600, by = b.y * 1066;
    const dx = bx - ax, dy = by - ay;
    const t = ((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy);
    if (t <= 1e-8 || t >= 1 - 1e-8 || Math.hypot(ax + t * dx - x, ay + t * dy - y) > 0.8) continue;
    changed.push([key, edge]);
  }
  if (!changed.length) throw new Error(`Unused community junction: ${id}`);
  nodes.set(id, { id, ...p });
  for (const [key, edge] of changed) {
    edges.delete(key);
    for (const [from, to] of [[edge.from, id], [id, edge.to]]) {
      edges.set([from, to].sort().join(":"), { ...edge, from, to });
    }
  }
}

