const nodes = new Map(), edges = new Map();
function road(points, modes = ["walk", "bike", "car"]) {
  const ids = points.map(([x, y]) => {
    const id = anchors.get(`${x},${y}`) ?? `c${x}-${y}`;
    if (!nodes.has(id)) nodes.set(id, { id, ...communityPoint(x, y) });
    return id;
  });
  for (let i = 1; i < ids.length; i++) {
    const key = [ids[i - 1], ids[i]].sort().join(":");
    if (edges.has(key)) {
      if (edges.get(key).modes.join() !== modes.join()) throw new Error(`Conflicting community street: ${key}`);
      continue;
    }
    edges.set(key, { from: ids[i - 1], to: ids[i], modes });
  }
}

